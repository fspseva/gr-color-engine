#!/usr/bin/env python3
"""Fit the v2.25 engine operators from pixel-aligned pairs.

Each operator is `out_lin = g(M · in_lin)`: a 3×3 matrix in linear light and
three per-channel curves (12 knots at gamma-spaced positions KX), fitted
from the Standard/Daylight/zero JPEG (R0002790) to one development.
Tone sliders (Key, Contrast, Contrast Hi/Sh) are curves only (M = I).
WB shift sides at 7/14 steps, WB modes, and colour-control base looks get
the full form. Then composition order and step interpolation are validated
against the pair developments, and src/lib/engine/ops.generated.ts is written.

  python3 scripts/fit-ops.py [--quick]     (quick: fewer pixels)
"""
import json, os, sys, importlib.util, time
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location('fs', os.path.join(ROOT, 'scripts/fit-separable.py'))
fs = importlib.util.module_from_spec(spec); spec.loader.exec_module(fs)
from scipy.optimize import least_squares

QUICK = '--quick' in sys.argv
N_FIT, N_EVAL, SEED = (25000 if QUICK else 50000), 300000, 0
KX = fs.KX; KN = fs.KNOTS
C = 'test-images/control'

# name -> (file id, tone-only?)
OPS = {
    'key:-4': ('R0002802', True), 'key:-2': ('R0002805', True), 'key:2': ('R0002806', True), 'key:4': ('R0002807', True),
    'contrast:-4': ('R0002808', True), 'contrast:-2': ('R0002809', True), 'contrast:2': ('R0002810', True), 'contrast:4': ('R0002811', True),
    'chi:-4': ('R0002812', True), 'chi:-2': ('R0002813', True), 'chi:2': ('R0002814', True), 'chi:4': ('R0002815', True),
    'csh:-4': ('R0002816', True), 'csh:-2': ('R0002817', True), 'csh:2': ('R0002818', True), 'csh:4': ('R0002819', True),
    'wb:A7': ('R0003658', False), 'wb:A14': ('R0003659', False), 'wb:B7': ('R0003660', False), 'wb:B14': ('R0003662', False),
    'wb:G7': ('R0003689', False), 'wb:G14': ('R0003647', False), 'wb:M7': ('R0003656', False), 'wb:M14': ('R0003657', False),
    'mode:shade': ('R0003682', False), 'mode:cloudy': ('R0003683', False), 'mode:tungsten': ('R0003684', False), 'mode:fl-daylight': ('R0003685', False),
    'base:vivid': ('R0003217', False), 'base:positive-film': ('R0003225', False), 'base:negative-film': ('R0003010', False),
    'base:bleach-bypass': ('R0003232', False), 'base:retro': ('R0003240', False), 'base:cross-processing': ('R0003256', False),
}
PAIRS = {  # validation: camera development of a combination -> candidate op orders
    'R0002872 Key+4 Con-4': [['key:4', 'contrast:-4'], ['contrast:-4', 'key:4']],
    'R0002870 Con+4 CHi+4': [['contrast:4', 'chi:4'], ['chi:4', 'contrast:4']],
    'R0002871 Con+4 CSh-4': [['contrast:4', 'csh:-4'], ['csh:-4', 'contrast:4']],
    'R0003793 M14:A14': [['wb:M14', 'wb:A14'], ['wb:A14', 'wb:M14']],
    'R0003801 NF M14': [['base:negative-film', 'wb:M14'], ['wb:M14', 'base:negative-film']],
    'R0003696 PF M7': [['base:positive-film', 'wb:M7'], ['wb:M7', 'base:positive-film']],
    'R0003700 NF G14': [['base:negative-film', 'wb:G14'], ['wb:G14', 'base:negative-film']],
}


def full(id_):
    return np.asarray(Image.open(fs.find_file(id_)).convert('RGB'), np.uint8).reshape(-1, 3)


def apply_op(op, x_lin):
    M = np.array(op['m']).reshape(3, 3); k = np.array(op['k']).reshape(3, KN)
    y = x_lin @ M.T
    return np.stack([np.interp(np.clip(y[:, c], 0, 1), KX, k[c]) for c in range(3)], 1)


def chain(ops, x8):
    x = fs.lin(x8 / 255.0)
    for op in ops:
        x = apply_op(op, x)
    return fs.srgb(x) * 255


def monotone(k):
    return np.maximum.accumulate(np.maximum(k, 0), axis=-1)


def fit_op(inp8, out8, tone_only):
    x = fs.lin(inp8 / 255.0); t = out8.astype(np.float32)
    if tone_only:
        th0 = np.concatenate([KX] * 3)
        f = lambda th: (fs.srgb(np.stack([np.interp(x[:, c], KX, th[c * KN:(c + 1) * KN]) for c in range(3)], 1)) * 255 - t).ravel()
        res = least_squares(f, th0, method='trf', max_nfev=80, x_scale='jac')
        return dict(m=np.eye(3).ravel().tolist(), k=monotone(res.x.reshape(3, KN)).ravel().tolist())
    th = fs.fit_B(inp8, out8, pre=False)
    return dict(m=th[:9].tolist(), k=monotone(th[9:].reshape(3, KN)).ravel().tolist())


def interp_op(a, b, t):
    """Linear interpolation between two ops (a at t=0, b at t=1)."""
    return dict(m=((1 - t) * np.array(a['m']) + t * np.array(b['m'])).tolist(), k=((1 - t) * np.array(a['k']) + t * np.array(b['k'])).tolist())


IDENT = dict(m=np.eye(3).ravel().tolist(), k=np.concatenate([KX] * 3).tolist())


def fmt(v):
    if abs(v) < 5e-7: return '0'
    s = f"{v:.6g}"
    return s if ('.' in s or 'e' in s) else s + '.0'


def emit(ops):
    lines = ["// GENERATED by scripts/fit-ops.py from in-camera developments of R0002785 — do not hand-edit.",
             "// Each operator: out_lin = g(M · in_lin); `m` is the 3×3 row-major matrix in linear light,",
             "// `k` the three per-channel output curves (36 values: 3 × 12 knots at gamma-spaced input",
             "// positions (i/11)^2.2). Fitted on 50k pixel pairs, scored on 300k (see calibration/ops/).",
             "import type { ColorOp } from './ops';", "", "export const OPS: Record<string, ColorOp> = {"]
    for name, op in ops.items():
        lines.append(f"  '{name}': {{")
        lines.append("    m: [" + ', '.join(fmt(v) for v in op['m']) + "],")
        lines.append("    k: [" + ', '.join(fmt(v) for v in op['k']) + "],")
        lines.append("  },")
    lines.append("};")
    open(os.path.join(ROOT, 'src/lib/engine/ops.generated.ts'), 'w').write('\n'.join(lines) + '\n')


def main():
    os.makedirs(os.path.join(ROOT, 'calibration/ops'), exist_ok=True)
    base = full('R0002790')
    rng = np.random.default_rng(SEED); idx = rng.choice(len(base), N_EVAL, replace=False); fit_idx = idx[:N_FIT]
    inp_fit, inp_eval = base[fit_idx], base[idx]
    ops, scores = {}, {}
    t0 = time.time()
    for name, (id_, tone) in OPS.items():
        out = full(id_)
        op = fit_op(inp_fit, out[fit_idx], tone)
        pred = chain([op], inp_eval)
        r = float(np.sqrt(((pred - out[idx]) ** 2).mean()))
        ops[name] = op; scores[name] = r
        print(f"{name:24} {id_}  rms {r:5.2f}   ({time.time() - t0:5.0f}s)", flush=True)
    json.dump(dict(ops=ops, scores=scores, n_fit=N_FIT, n_eval=N_EVAL), open(os.path.join(ROOT, 'calibration/ops/ops.json'), 'w'))
    emit(ops)

    print("\n--- composition order (RGB RMS vs camera pair development; lower = that order) ---", flush=True)
    comp = {}
    for label, orders in PAIRS.items():
        cam = full(label.split()[0])[idx]
        res = [float(np.sqrt(((chain([ops[n] for n in o], inp_eval) - cam) ** 2).mean())) for o in orders]
        comp[label] = dict(zip([' → '.join(o) for o in orders], res))
        print(f"{label:22} " + '   '.join(f"{' → '.join(o)}: {r:5.2f}" for o, r in zip(orders, res)), flush=True)

    print("\n--- step interpolation (predict the ±2 / 7-step developments from neighbours) ---", flush=True)
    interp = {}
    for name, (id_, _) in OPS.items():
        fam, lvl = name.split(':')
        if fam in ('key', 'contrast', 'chi', 'csh') and lvl in ('-2', '2'):
            far = ops[f"{fam}:{int(lvl) * 2}"]; pred_op = interp_op(IDENT, far, 0.5)
        elif fam == 'wb' and lvl.endswith('7'):
            far = ops[f"wb:{lvl[0]}14"]; pred_op = interp_op(IDENT, far, 0.5)
        else:
            continue
        cam = full(id_)[idx]
        r = float(np.sqrt(((chain([pred_op], inp_eval) - cam) ** 2).mean()))
        interp[name] = dict(interpolated=r, direct=scores[name])
        print(f"{name:14} interpolated from the outer level: {r:5.2f}   (direct fit {scores[name]:5.2f})", flush=True)
    json.dump(dict(composition=comp, interpolation=interp), open(os.path.join(ROOT, 'calibration/ops/validation.json'), 'w'), indent=1)


if __name__ == '__main__' and '--canon' not in sys.argv:
    main()


# ---------------------------------------------------------------------------
# Canonical split between matrix and curves. A fitted op is ambiguous: any
# per-channel scale can move between a matrix row and that channel's curve.
# Interpolating toward identity (intermediate slider steps) only behaves if
# the curves are as close to identity as possible and the matrix carries the
# gain. `python3 scripts/fit-ops.py --canon` rewrites ops.json and the TS.
def canonicalize(op):
    if np.allclose(np.array(op['m']).reshape(3, 3), np.eye(3), atol=1e-9):
        return op
    M = np.array(op['m']).reshape(3, 3); k = np.array(op['k']).reshape(3, KN)
    ys = np.linspace(0, 1, 200)
    newM = M.copy(); newk = k.copy()
    for c in range(3):
        best = (np.inf, 1.0)
        for s in np.exp(np.linspace(np.log(0.15), np.log(6.0), 400)):
            yy = ys[ys * s <= 1.0]
            if len(yy) < 40: continue
            g = np.interp(yy * s, KX, k[c])
            err = np.mean((g - yy) ** 2) + 0.02 * (1 - len(yy) / len(ys))  # prefer covering the range
            if err < best[0]: best = (err, s)
        s = best[1]
        newM[c] /= s
        newk[c] = np.interp(np.clip(KX * s, 0, 1), KX, k[c])  # g'(y) = g(s·y)
        if s > 1:  # g' beyond 1/s is extrapolated flat by the clip above; extend linearly instead
            slope = (k[c][-1] - k[c][-2]) / (KX[-1] - KX[-2])
            over = KX * s > 1
            newk[c][over] = k[c][-1] + slope * (KX[over] * s - 1)
    return dict(m=newM.ravel().tolist(), k=newk.ravel().tolist())


if __name__ == '__main__' and '--canon' in sys.argv:
    J = json.load(open(os.path.join(ROOT, 'calibration/ops/ops.json')))
    ops = {n: canonicalize(o) for n, o in J['ops'].items()}
    base = full('R0002790')
    rng = np.random.default_rng(SEED); idx = rng.choice(len(base), N_EVAL, replace=False); inp_eval = base[idx]
    print("canonicalized: op unchanged?  and interpolation of the 7-step / ±2 points from the outer level")
    for name, (id_, _) in OPS.items():
        cam = full(id_)[idx]
        r_direct = float(np.sqrt(((chain([ops[name]], inp_eval) - cam) ** 2).mean()))
        fam, lvl = name.split(':')
        r_interp = None
        if fam in ('key', 'contrast', 'chi', 'csh') and lvl in ('-2', '2'):
            r_interp = float(np.sqrt(((chain([interp_op(IDENT, ops[f"{fam}:{int(lvl) * 2}"], 0.5)], inp_eval) - cam) ** 2).mean()))
        elif fam == 'wb' and lvl.endswith('7'):
            r_interp = float(np.sqrt(((chain([interp_op(IDENT, ops[f"wb:{lvl[0]}14"], 0.5)], inp_eval) - cam) ** 2).mean()))
            r_mid = float(np.sqrt(((chain([interp_op(ops[name], ops[f"wb:{lvl[0]}14"], 0.5)], inp_eval) - full(id_)[idx]) ** 2).mean()))
        print(f"{name:24} direct {r_direct:5.2f}  (was {J['scores'][name]:5.2f})" + (f"   half-way from outer level: {r_interp:6.2f}" if r_interp is not None else ''), flush=True)
    J['ops'] = ops; J['canonical'] = True
    json.dump(J, open(os.path.join(ROOT, 'calibration/ops/ops.json'), 'w'))
    emit(ops)
    print('emitted src/lib/engine/ops.generated.ts')
